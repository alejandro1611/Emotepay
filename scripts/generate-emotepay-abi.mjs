import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";

const artifactPath = resolve(
  process.cwd(),
  "artifacts/contracts/EmotePay.sol/EmotePay.json",
);
const outputPath = resolve(process.cwd(), "lib/generated/emotePayAbi.ts");
const artifact = JSON.parse(readFileSync(artifactPath, "utf8"));

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(
  outputPath,
  `// Generated by scripts/generate-emotepay-abi.mjs from Hardhat artifacts.\n` +
    `// Do not edit this file manually.\n` +
    `export const emotePayAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`,
);
